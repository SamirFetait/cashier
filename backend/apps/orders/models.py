from decimal import Decimal

from django.conf import settings
from django.db import models

from apps.common.fields import money_field, quantity_field


class Order(models.Model):
    class Status(models.TextChoices):
        COMPLETED = "COMPLETED", "Completed"
        CANCELLED = "CANCELLED", "Cancelled"
        VOIDED = "VOIDED", "Voided"
        REFUNDED = "REFUNDED", "Fully refunded"
        PARTIALLY_REFUNDED = "PARTIALLY_REFUNDED", "Partially refunded"

    class Payment(models.TextChoices):
        CASH = "CASH", "Cash"
        CARD = "CARD", "Card"
        OTHER = "OTHER", "Other"

    receipt_number = models.CharField(
        max_length=32, unique=True, null=True, blank=True, db_index=True,
        help_text="Sequential, gapless document number shown on the receipt",
    )
    # Generated by the terminal before the sale is sent. A till that sold
    # offline replays its queue on reconnect, and a retry that crosses with a
    # slow success must not post the sale twice.
    client_uuid = models.UUIDField(
        null=True, blank=True, unique=True, db_index=True,
        help_text="Terminal-generated id used to make checkout idempotent",
    )
    # True when the sale was rung up with no connection and synced later.
    was_offline = models.BooleanField(default=False)
    customer = models.ForeignKey(
        "customers.Customer", on_delete=models.SET_NULL,
        null=True, blank=True, related_name="orders",
    )
    storage = models.ForeignKey(
        "inventory.Storage", on_delete=models.PROTECT, related_name="orders"
    )
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, related_name="orders",
    )
    shift = models.ForeignKey(
        "shifts.Shift", on_delete=models.PROTECT,
        null=True, blank=True, related_name="orders",
        help_text="Till session this sale belongs to",
    )
    status = models.CharField(
        max_length=20, choices=Status.choices, default=Status.COMPLETED
    )
    payment_method = models.CharField(
        max_length=20, choices=Payment.choices, default=Payment.CASH
    )
    subtotal = money_field(default=Decimal("0"), help_text="Sum of line totals before order discount")
    discount = money_field(default=Decimal("0"), help_text="Order-level discount")
    tax = money_field(default=Decimal("0"))
    total = money_field(default=Decimal("0"))
    note = models.CharField(max_length=255, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"Order {self.receipt_number or f'#{self.pk}'} — {self.total}"

    @property
    def amount_paid(self) -> Decimal:
        return sum((p.amount for p in self.payments.all()), Decimal("0"))

    @property
    def change_given(self) -> Decimal:
        return sum((p.change for p in self.payments.all()), Decimal("0"))

    @property
    def line_discount_total(self) -> Decimal:
        return sum((i.discount for i in self.items.all()), Decimal("0"))

    @property
    def cost_total(self) -> Decimal:
        return sum((i.unit_cost * i.quantity for i in self.items.all()), Decimal("0"))

    @property
    def gross_margin(self) -> Decimal:
        return self.total - self.tax - self.cost_total


class Return(models.Model):
    """A refund document raised against a completed sale.

    Kept separate from the Order so the original receipt is never rewritten.
    """

    number = models.CharField(max_length=32, unique=True, db_index=True)
    order = models.ForeignKey(Order, on_delete=models.PROTECT, related_name="returns")
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, related_name="returns_created",
    )
    shift = models.ForeignKey(
        "shifts.Shift", on_delete=models.PROTECT,
        null=True, blank=True, related_name="returns",
    )
    refund_method = models.CharField(max_length=20, choices=[
        ("CASH", "Cash"), ("CARD", "Card"), ("MOBILE", "Mobile / wallet"),
        ("VOUCHER", "Voucher"), ("OTHER", "Other"),
    ])
    total = money_field(default=Decimal("0"))
    reason = models.CharField(max_length=255)
    restocked = models.BooleanField(
        default=True, help_text="False when goods came back damaged and were written off"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"Return {self.number} — {self.total}"


class ReturnItem(models.Model):
    return_doc = models.ForeignKey(Return, on_delete=models.CASCADE, related_name="items")
    order_item = models.ForeignKey(
        "orders.OrderItem", on_delete=models.PROTECT, related_name="return_items"
    )
    product = models.ForeignKey(
        "products.Product", on_delete=models.PROTECT, related_name="return_items"
    )
    quantity = quantity_field()
    unit_refund = money_field()
    line_refund = money_field()

    def __str__(self) -> str:
        return f"{self.quantity} x {self.product} refunded"


class Payment(models.Model):
    """One tender against an order. An order may have several (split payment)."""

    class Method(models.TextChoices):
        CASH = "CASH", "Cash"
        CARD = "CARD", "Card"
        MOBILE = "MOBILE", "Mobile / wallet"
        VOUCHER = "VOUCHER", "Voucher"
        OTHER = "OTHER", "Other"

    order = models.ForeignKey(Order, on_delete=models.CASCADE, related_name="payments")
    method = models.CharField(max_length=20, choices=Method.choices)
    amount = money_field(help_text="Amount applied to the order total")
    # For cash: what the customer handed over, and what went back to them.
    # tendered - change == amount, so the drawer maths always balances.
    tendered = money_field(default=Decimal("0"))
    change = money_field(default=Decimal("0"))
    reference = models.CharField(
        max_length=120, blank=True, help_text="Card auth code / transaction id"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]

    def __str__(self) -> str:
        return f"{self.get_method_display()} {self.amount}"


class OrderItem(models.Model):
    order = models.ForeignKey(Order, on_delete=models.CASCADE, related_name="items")
    product = models.ForeignKey(
        "products.Product", on_delete=models.PROTECT, related_name="order_items"
    )
    quantity = quantity_field()
    unit_price = money_field()
    # Snapshot of cost at time of sale, so margin reports stay accurate even
    # after Product.cost is edited.
    unit_cost = money_field(default=Decimal("0"))
    discount = money_field(default=Decimal("0"), help_text="Discount applied to this line")
    line_total = money_field(help_text="quantity * unit_price - discount")

    @property
    def gross_margin(self) -> Decimal:
        return self.line_total - (self.unit_cost * self.quantity)

    def __str__(self) -> str:
        return f"{self.quantity} x {self.product} @ {self.unit_price}"
